"""Emit ``<Prefix>Dialect.td``: the dialect definition itself.

The smallest of the three artifacts and the one every other generated file
includes. It declares the mnemonic namespace an op's name is resolved in
(``acme`` -> ``acme.stream.create``), the C++ namespace the generated classes
land in, and that the dialect parses and prints its own types.
"""

__all__ = ["render_dialect_td"]

_DIALECT_TD = """\
#ifndef {guard}_DIALECT_TD
#define {guard}_DIALECT_TD

include "mlir/IR/DialectBase.td"

def {prefix}_Dialect : Dialect {{
  let name = "{dialect}";
  let summary = "{summary}";
  let description = [{{
    {description}
  }}];
  let cppNamespace = "::mlir::{dialect}";
  let useDefaultTypePrinterParser = 1;
}}

#endif // {guard}_DIALECT_TD
"""


def render_dialect_td(options) -> str:
    """The dialect definition every other generated file includes.

    ``cppNamespace`` is derived from the dialect name rather than configured
    separately: the generated C++ has to agree with it, and two spellings of
    one fact can disagree.
    """
    return _DIALECT_TD.format(
        guard=options.dialect_name.upper(),
        prefix=options.cpp_class_prefix,
        dialect=options.dialect_name,
        summary=getattr(options, "summary", "")
        or f"{options.dialect_name} dialect",
        description=(
            getattr(options, "description", "")
            or f"Autogenerated FFI mirror of the {options.dialect_name} API."
        ),
    )
